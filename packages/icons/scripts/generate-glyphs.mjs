// Writes src/glyphs.ts: every built-in icon as its own named export (`chevronDownIcon`, ...), as a
// plain object literal, so a bundler keeps only the icons an app imports (without the search-only
// tags and categories), and src/names.ts: the `IconName` type, every built-in name. Run after changing
// src/definitions.ts:  node packages/icons/scripts/generate-glyphs.mjs  (a test checks both are current).
import { build } from 'esbuild';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function exportName(iconName) {
  const camel = iconName.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase());
  return `${/^[0-9]/.test(camel) ? `icon${camel}` : camel}Icon`;
}

async function loadDefinitions() {
  const dir = mkdtempSync(join(tmpdir(), 'editora-glyphs-'));
  try {
    const out = join(dir, 'definitions.mjs');
    await build({ entryPoints: [join(root, 'src/definitions.ts')], bundle: true, format: 'esm', platform: 'neutral', outfile: out, logLevel: 'silent' });
    return (await import(pathToFileURL(out).href)).iconDefinitions;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

export async function renderNamesModule() {
  const names = [...new Set((await loadDefinitions()).map((definition) => definition.name))].sort();
  return [
    '// Generated by scripts/generate-glyphs.mjs from definitions.ts. Do not edit by hand.',
    '',
    '/**',
    ' * The name of a built-in icon. Functions that take a name accept any string too (an alias such as',
    " * `close` for `x`, or an icon you registered), so this is for autocomplete, and for typing names that",
    ' * come from your own data, where a typo becomes a compile error.',
    ' */',
    'export type IconName =',
    ...names.map((name, index) => `  | '${name}'${index === names.length - 1 ? ';' : ''}`),
  ].join('\n') + '\n';
}

export async function renderGlyphsModule() {
  const iconDefinitions = await loadDefinitions();
  const seen = new Map();
  const lines = [
    '// Generated by scripts/generate-glyphs.mjs from definitions.ts. Do not edit by hand.',
    "import type { IconDefinition } from './types';",
    '',
  ];
  for (const definition of iconDefinitions) {
    const name = exportName(definition.name);
    if (seen.has(name)) throw new Error(`"${definition.name}" and "${seen.get(name)}" both export as ${name}`);
    seen.set(name, definition.name);
    // tags/categories only serve icon search, which needs the whole set anyway.
    const { tags, categories, ...glyph } = definition;
    lines.push(`export const ${name}: IconDefinition = ${JSON.stringify(glyph)};`);
  }
  return lines.join('\n') + '\n';
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const source = await renderGlyphsModule();
  writeFileSync(join(root, 'src/glyphs.ts'), source);
  console.log(`wrote src/glyphs.ts (${source.split('\n').length - 4} icons)`);
  writeFileSync(join(root, 'src/names.ts'), await renderNamesModule());
  console.log('wrote src/names.ts');
}
