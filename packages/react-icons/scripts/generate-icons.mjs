// Writes src/icons.tsx: one component per built-in icon (CheckIcon, ...), each built from its own glyph in
// @editora/icons/glyphs, so a bundler keeps only the components an app imports. Run after the icon set
// changes (after packages/icons/scripts/generate-glyphs.mjs):
//   node packages/react-icons/scripts/generate-icons.mjs   (a test checks src/icons.tsx is current).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const glyphsSource = join(root, '../icons/src/glyphs.ts');

// Components published before the set was cleaned up, under a name that is now an alias. Kept so imports
// keep working; each draws the icon its old name points to.
const LEGACY = [
  { key: 'nav', component: 'NavIcon', target: 'navigation' },
  { key: 'navigation-icon', component: 'NavigationMenuIcon', target: 'navigation' },
  { key: 'airplan', component: 'AirplanIcon', target: 'airplane' },
];

export function componentName(iconName) {
  return iconName
    .split(/[-_\s]+/g)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('') + 'Icon';
}

export function renderIconsModule() {
  const glyphs = [...readFileSync(glyphsSource, 'utf8').matchAll(/^export const (\w+): IconDefinition = \{"name":"([^"]+)"/gm)].map(
    ([, glyph, name]) => ({ glyph, name })
  );
  if (!glyphs.length) throw new Error(`no glyphs found in ${glyphsSource}`);

  const entries = [];
  for (const { glyph, name } of glyphs) {
    entries.push({ key: name, component: componentName(name), glyph });
    for (const legacy of LEGACY.filter((item) => item.target === name)) entries.push({ ...legacy, glyph });
  }
  for (const legacy of LEGACY) {
    if (!glyphs.some((item) => item.name === legacy.target)) throw new Error(`${legacy.component}: no icon "${legacy.target}"`);
  }
  const seen = new Set();
  for (const { component } of entries) {
    if (seen.has(component)) throw new Error(`two icons are both ${component}`);
    seen.add(component);
  }

  const imports = [...new Set(entries.map((entry) => entry.glyph))];
  return [
    '// Generated by scripts/generate-icons.mjs from @editora/icons/glyphs. Do not edit by hand.',
    "import { builtInIcon } from './defineIcon';",
    "import type { IconComponent } from './types';",
    'import {',
    ...imports.map((glyph) => `  ${glyph},`),
    "} from '@editora/icons/glyphs';",
    '',
    // The annotation lets a bundler drop every component an app does not import.
    ...entries.map(({ component, glyph }) => `export const ${component}: IconComponent = /*#__PURE__*/ builtInIcon(${glyph}, '${component}');`),
    '',
    'export const icons = {',
    ...entries.map(({ key, component }) => `  '${key}': ${component},`),
    '} as const;',
    '',
    'export type IconName = keyof typeof icons;',
    'export type IconsMap = typeof icons;',
    '',
    'export const iconNames = /*#__PURE__*/ Object.keys(icons) as IconName[];',
    '',
    'export const Icons: IconsMap = icons;',
    '',
    'export function getIconComponent(name: IconName): IconComponent {',
    '  return icons[name];',
    '}',
  ].join('\n') + '\n';
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(join(root, 'src/icons.tsx'), renderIconsModule());
  console.log('wrote src/icons.tsx');
}
