import type { SidebarsConfig } from "@docusaurus/plugin-content-docs";

/**
 * A section inside one of the top-level groups, with its own index page.
 * The slug keeps the /docs/category/<slug> URL each section had before the
 * sidebar was regrouped; those URLs are indexed and linked from outside.
 */
function section(label: string, dirName: string, slug: string, description: string) {
  return {
    type: "category" as const,
    label,
    link: { type: "generated-index" as const, title: label, slug: `/category/${slug}`, description },
    items: [{ type: "autogenerated" as const, dirName }],
  };
}

